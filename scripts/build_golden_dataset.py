from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_TEXT = ROOT / "data/demo/eval_queries.jsonl"
SOURCE_IMAGE = ROOT / "data/demo/image_eval.jsonl"
OUTPUT = ROOT / "evaluation/golden_queries.jsonl"


def language_for(row: dict) -> str:
    query_type = row.get("type", "")
    if query_type == "hindi":
        return "hi"
    if query_type == "hinglish":
        return "hinglish"
    return "en"


def main() -> None:
    output: list[dict] = []
    text_rows = [json.loads(line) for line in SOURCE_TEXT.read_text(encoding="utf-8").splitlines() if line.strip()]
    for index, row in enumerate(text_rows, 1):
        relevance = {str(key): int(value) for key, value in row["relevance"].items()}
        output.append(
            {
                "query_id": f"text-{index:03d}",
                "query": row["query"],
                "language": language_for(row),
                "modality": "text",
                "query_type": row.get("type", "unknown"),
                "relevant_document_ids": list(relevance),
                "graded_relevance": relevance,
                "notes": "Manually curated repository demo relevance label migrated from data/demo/eval_queries.jsonl.",
            }
        )

    # Telugu is intentionally an evaluation slice, not a preprocessing claim.
    # Relevance mappings are manually curated from the existing catalog semantics.
    telugu = [
        ("నల్ల రన్నింగ్ షూస్", "semantic", {"SHO-001": 3, "SHO-005": 2, "SHO-007": 2, "SHO-018": 2}),
        ("వైర్‌లెస్ ఇయర్‌బడ్స్", "semantic", {"ELE-001": 3, "ELE-002": 2, "ELE-003": 2, "ELE-004": 2}),
        ("నీలం కుర్తీ", "semantic", {"APP-001": 3, "APP-004": 2}),
        ("ల్యాప్‌టాప్ బ్యాక్‌ప్యాక్", "semantic", {"BAG-001": 2, "BAG-002": 3, "BAG-003": 3}),
        ("ఫిట్‌నెస్ స్మార్ట్‌వాచ్", "semantic", {"WAT-004": 3, "WAT-010": 2}),
        ("స్టీల్ వాటర్ బాటిల్", "semantic", {"HOM-003": 3}),
    ]
    for index, (query, query_type, relevance) in enumerate(telugu, 1):
        output.append(
            {
                "query_id": f"telugu-{index:03d}",
                "query": query,
                "language": "te",
                "modality": "text",
                "query_type": query_type,
                "relevant_document_ids": list(relevance),
                "graded_relevance": relevance,
                "notes": "Manually curated Telugu evaluation query. FindX has no Telugu rewrite table; this measures the multilingual dense model/corpus behaviour directly.",
            }
        )

    image_rows = [json.loads(line) for line in SOURCE_IMAGE.read_text(encoding="utf-8").splitlines() if line.strip()]
    for index, row in enumerate(image_rows, 1):
        relevant = {doc_id: 1 for doc_id in row["relevant_product_ids"]}
        output.append(
            {
                "query_id": f"image-{index:03d}",
                "query": "",
                "language": "none",
                "modality": "image",
                "query_type": "image_to_image",
                "query_image_id": row["query_product_id"],
                "relevant_document_ids": list(relevant),
                "graded_relevance": relevant,
                "notes": f"Repository-authored visual proxy label: {row.get('label_rule', '')}. Query item itself is excluded.",
            }
        )

    multimodal = [
        ("SHO-001", "similar but blue under 3000", {"SHO-002": 3, "SHO-008": 2, "SHO-017": 2}),
        ("ELE-001", "similar but blue", {"ELE-004": 3}),
        ("BAG-001", "similar but blue", {"BAG-002": 3, "BAG-003": 2}),
        ("WAT-003", "similar but blue", {"WAT-004": 3}),
        ("APP-002", "similar but blue cotton", {"APP-001": 3, "APP-004": 2}),
        ("SHO-002", "similar but black under 3000", {"SHO-001": 3, "SHO-005": 2, "SHO-018": 2}),
    ]
    for index, (query_image_id, query, relevance) in enumerate(multimodal, 1):
        output.append(
            {
                "query_id": f"multimodal-{index:03d}",
                "query": query,
                "language": "en",
                "modality": "multimodal",
                "query_type": "image_plus_text",
                "query_image_id": query_image_id,
                "relevant_document_ids": list(relevance),
                "graded_relevance": relevance,
                "notes": "Manually curated from catalog colour/category/price semantics; not generated by the retrieval system.",
            }
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(json.dumps(row, ensure_ascii=False) for row in output) + "\n", encoding="utf-8")
    print(f"wrote {len(output)} golden queries to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
